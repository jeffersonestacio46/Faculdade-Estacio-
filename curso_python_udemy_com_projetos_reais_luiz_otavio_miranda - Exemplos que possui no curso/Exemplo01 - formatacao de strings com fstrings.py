variavel = 'ABC'
print(f'{variavel}')
print(f'{variavel: >10}.')#Pular 10 caracteries para direita
print(f'{variavel: <10}.')#o ponto serve para mostrar quantos caracteries pulou
print(f'{variavel:$^10}.')#Vai centralizar# Está com o $ paras mostrar os espaços preenchidos#Podemos fazer titulos
print(f'{1000.1654646844988494:0=+10,.1f}')#O sinal de igual força o nomero aparecer depois do 0
print(f'O hexadecial de 1500 é {1500:08X}')#Podemos usar maiusculo e minusculo com o x maiusculo ou minusculo
